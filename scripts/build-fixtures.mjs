// SPEC-FIGMA-003 fixture builder. Generates 30-frame mock-30frame/ fixture
// directory + subset-5.json. Idempotent — safe to re-run.

import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const FIXTURE_DIR = join(ROOT, "tests/fixtures/mock-30frame");

// Minimal valid PNG (1x1 transparent). Source: well-known PNG signature +
// minimal IHDR/IDAT/IEND. ~70 bytes. Mock provider does not decode it.
const MIN_PNG = Buffer.from(
  "89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c4890000000a49444154789c63000100000005000100" +
    "0d0a2db40000000049454e44ae426082",
  "hex",
);

const DOMAINS = ["AUTH", "DASH", "SETTINGS", "PROFILE", "BILLING"];

function screenIdAt(i) {
  // F00..F29 — matches test helper makeFrames pattern
  return `F${String(i).padStart(2, "0")}`;
}

function domainScreenIdAt(i) {
  // 5 domains × 6 frames = 30. Used for fixture content tagging only.
  const domain = DOMAINS[Math.floor(i / 6)];
  return `${domain}-${String((i % 6) + 1).padStart(2, "0")}`;
}

function defaultResponse(i) {
  // 21 frames at confidence 0.8 (no Vision retry), 9 at 0.5 (Vision retry).
  const confidence = i <= 20 ? 0.8 : 0.5;
  const intent = `프레임 ${domainScreenIdAt(i)} 의도`;
  return {
    text: JSON.stringify({
      intent,
      user_value: "사용자가 화면에서 핵심 가치를 얻는다",
      success_criteria: "PM 검수 통과",
      states: ["default"],
      edge_cases: ["empty data"],
      data_io: ["GET /resource"],
      intent_mismatch: false,
    }),
    input_tokens: 1500,
    output_tokens: 400,
    confidence,
    intent_mismatch: false,
  };
}

function ensureDir(path) {
  if (!existsSync(path)) mkdirSync(path, { recursive: true });
}

function writeFrameDir(i) {
  const sid = screenIdAt(i);
  const dir = join(FIXTURE_DIR, sid);
  ensureDir(dir);
  writeFileSync(join(dir, "screenshot.png"), MIN_PNG);
  writeFileSync(
    join(dir, "response.json"),
    JSON.stringify(defaultResponse(i), null, 2),
  );
}

function writeSubset5() {
  // For AC-S8 substitutability oracle (mock vs RecordedAnthropicProvider).
  // Both providers must replay these exact 5 entries with identical key sets.
  const frames = Array.from({ length: 5 }, (_, i) => ({
    screen_id: screenIdAt(i),
    source_hash: "abc123def456",
    response: defaultResponse(i),
  }));
  writeFileSync(
    join(FIXTURE_DIR, "subset-5.json"),
    JSON.stringify({ frames }, null, 2),
  );
}

function writeReadme() {
  const md = `# mock-30frame fixture

Generated by \`scripts/build-fixtures.mjs\`. Do not edit by hand — re-run the script.

- 30 frame directories \`F00..F29\`, each with \`response.json\` + minimal \`screenshot.png\`
- \`subset-5.json\` for AC-S8 substitutability oracle
- Confidence distribution: 21 frames at 0.8 (no Vision retry), 9 frames at 0.5 (Vision retry)
`;
  writeFileSync(join(FIXTURE_DIR, "README.md"), md);
}

ensureDir(FIXTURE_DIR);
for (let i = 0; i < 30; i++) writeFrameDir(i);
writeSubset5();
writeReadme();

console.log(`fixtures: ${FIXTURE_DIR} (30 frames + subset-5.json)`);
